package com.nvidia.icms.inbound.rest.model.nvca;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@AllArgsConstructor
@NoArgsConstructor
@Builder
@Schema(description = "ImageConfig")
public class ImageConfig {

    @NotBlank(message = "Image repository must not be blank")
    @Schema(description = "Image repository")
    String repository;

    @NotBlank(message = "Image tag must not be blank")
    @Schema(description = "Image tag")
    String tag;
}
