use axum::extract::Request;
use axum::middleware::Next;
use axum::response::Response;
use http::{HeaderName, HeaderValue};

/// Names the component that produced an error (4xx or 5xx) response. Clients and the
/// vanity gateway read it to tell service errors from errors relayed from a
/// worker. The service owns this header: any value on a response before this
/// layer runs, including one supplied by a worker, is discarded.
pub(crate) const NVCF_ERROR_SOURCE: HeaderName = HeaderName::from_static("nvcf-error-source");

const INVOCATION_SERVICE: HeaderValue = HeaderValue::from_static("invocation_service");
const WORKER: HeaderValue = HeaderValue::from_static("worker");

/// Response extension set by handlers that relay a response produced by a worker.
/// Every other response is treated as generated by the invocation service.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct WorkerResponse;

/// Replaces `NVCF-Error-Source` on every response and sets it on 4xx and 5xx
/// responses to `worker` or `invocation_service`.
pub(crate) async fn error_source_middleware(request: Request, next: Next) -> Response {
    let mut response = next.run(request).await;
    // `remove` drops every value stored under the name, so repeated
    // worker-supplied copies are discarded too.
    response.headers_mut().remove(NVCF_ERROR_SOURCE);
    if response.status().is_client_error() || response.status().is_server_error() {
        let source = if response.extensions().get::<WorkerResponse>().is_some() {
            WORKER
        } else {
            INVOCATION_SERVICE
        };
        response.headers_mut().insert(NVCF_ERROR_SOURCE, source);
    }
    response
}

#[cfg(test)]
mod tests {
    use super::*;
    use axum::body::Body;
    use axum::middleware::from_fn;
    use axum::routing::get;
    use axum::Router;
    use http::{Request as HttpRequest, StatusCode};
    use tower::ServiceExt;

    fn spoofed_headers(status: StatusCode, worker: bool) -> Response {
        let mut response = Response::new(Body::empty());
        *response.status_mut() = status;
        response
            .headers_mut()
            .append(NVCF_ERROR_SOURCE, HeaderValue::from_static("spoofed"));
        response
            .headers_mut()
            .append(NVCF_ERROR_SOURCE, HeaderValue::from_static("worker"));
        if worker {
            response.extensions_mut().insert(WorkerResponse);
        }
        response
    }

    async fn serve(status: StatusCode, worker: bool) -> Response {
        let app = Router::new()
            .route(
                "/",
                get(move || async move { spoofed_headers(status, worker) }),
            )
            .layer(from_fn(error_source_middleware));
        app.oneshot(HttpRequest::get("/").body(Body::empty()).unwrap())
            .await
            .unwrap()
    }

    fn values(response: &Response) -> Vec<&str> {
        response
            .headers()
            .get_all(NVCF_ERROR_SOURCE)
            .iter()
            .map(|value| value.to_str().unwrap())
            .collect()
    }

    #[tokio::test]
    async fn worker_error_is_stamped_worker_and_spoofed_copies_are_removed() {
        for status in [StatusCode::BAD_REQUEST, StatusCode::INTERNAL_SERVER_ERROR] {
            let response = serve(status, true).await;
            assert_eq!(values(&response), vec!["worker"], "{status}");
        }
    }

    #[tokio::test]
    async fn service_error_is_stamped_invocation_service_even_with_spoofed_copies() {
        for status in [
            StatusCode::NOT_FOUND,
            StatusCode::TOO_MANY_REQUESTS,
            StatusCode::GATEWAY_TIMEOUT,
        ] {
            let response = serve(status, false).await;
            assert_eq!(values(&response), vec!["invocation_service"], "{status}");
        }
    }

    #[tokio::test]
    async fn non_error_responses_carry_no_error_source() {
        for (status, worker) in [
            (StatusCode::OK, true),
            (StatusCode::ACCEPTED, true),
            (StatusCode::FOUND, true),
            (StatusCode::OK, false),
        ] {
            let response = serve(status, worker).await;
            assert!(values(&response).is_empty(), "{status} worker={worker}");
        }
    }
}
