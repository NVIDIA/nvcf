type savedAPIKey struct {
	Service   string    `json:"service"`
	APIKey    string    `json:"apiKey"`
	ExpiresAt time.Time `json:"expiresAt"`
}

// savedAPIKeys lists the function, task and Event Ledger keys held in state.
func savedAPIKeys(s *state.State) []savedAPIKey {
	var keys []savedAPIKey
	for _, k := range []savedAPIKey{
		{"function", s.APIKey, s.APIKeyExpiration},
		{"task", s.NVCTAPIKey, s.NVCTAPIKeyExpiration},
		{"event-ledger", s.EventLedgerAPIKey, s.EventLedgerAPIKeyExpiration},
	} {
		if k.APIKey != "" {
			keys = append(keys, k)
		}
	}
	return keys
}

func runShowAPIKey(cmd *cobra.Command, args []string) error {
	// Load state
	if err := LoadStateForCurrentCommand(); err != nil {
		logging.Warning("Could not load existing state: %v", err)
	}

	keys := savedAPIKeys(GetCurrentState())

	if len(keys) == 0 {
		if IsJSONOutput() {
			return OutputJSON(map[string]interface{}{
				"hasKey": false,
			})
		}
		logging.Info("No API key found in state")
		logging.Plain("Use 'nvcf-cli api-key generate' to create one")
		return nil
	}

	if IsJSONOutput() {
		out := map[string]interface{}{
			"hasKey": true,
			"keys":   keys,
		}
		// Kept for callers that read the function key from the top level.
		for _, k := range keys {
			if k.Service == "function" {
				out["apiKey"] = k.APIKey
				out["expiresAt"] = k.ExpiresAt
			}
		}
		return OutputJSON(out)
	}

	logging.Success("Current saved API keys:")
	for _, k := range keys {
		logging.Plain("%s key: %s", k.Service, k.APIKey)
		if k.ExpiresAt.IsZero() {
			continue
		}
		if time.Now().After(k.ExpiresAt) {
			logging.Warning("  Expires: %s (EXPIRED)", k.ExpiresAt.Format("2006-01-02 15:04:05 MST"))
		} else {
			logging.Plain("  Expires: %s", k.ExpiresAt.Format("2006-01-02 15:04:05 MST"))
		}
	}

	return nil
}

// hasSavedAPIKeys reports whether state holds a function, task or Event Ledger key.
func hasSavedAPIKeys(s *state.State) bool {
	return len(savedAPIKeys(s)) > 0
}

// clearSavedAPIKeys drops the function, task and Event Ledger keys from state
// and keeps the admin token.
func clearSavedAPIKeys(s *state.State) {
	SetCurrentTokens(s.Token, "", s.TokenExpiration, time.Time{})
	sm := GetStateManagerForCurrentCommand()
	sm.ClearNVCTAPIKey()
	sm.ClearEventLedgerAPIKey()
}

func runClearAPIKey(cmd *cobra.Command, args []string) error {
	// Load state
	if err := LoadStateForCurrentCommand(); err != nil {
		logging.Warning("Could not load existing state: %v", err)
	}

	currentState := GetCurrentState()

	if !hasSavedAPIKeys(currentState) {
		if IsJSONOutput() {
			return OutputJSON(map[string]interface{}{
				"status": "no_key",
			})
		}
		logging.Info("No API key found in state to clear")
		return nil
	}

	// Confirmation prompt unless --force is used
	if !clearForce {
		logging.Warning("This will remove the API key from local state.")
		logging.Plain("The key itself remains valid but the CLI will no longer use it automatically.")
		logging.Plain("")

		if !promptForConfirmation("Are you sure you want to clear the saved API key?") {
			logging.Info("Clear cancelled.")
			return nil
		}
	}

	clearSavedAPIKeys(currentState)
	if err := SaveStateForCurrentCommand(); err != nil {
		return fmt.Errorf("failed to save cleared state: %w", err)
	}
	if IsJSONOutput() {
		return OutputJSON(map[string]interface{}{
			"status": "cleared",
		})
	}

	logging.Success("API key cleared from state")
	return nil
}

func runClearAllAPIKeys(cmd *cobra.Command, args []string) error {
	// Load configuration
	config, err := client.LoadConfig()
	if err != nil {
		return fmt.Errorf("failed to load configuration: %w", err)
	}

	// Optional explicit owner override (applies to all issuers when given).
	ownerOverride := ""
	if len(args) > 0 && args[0] != "" {
		ownerOverride = args[0]
	}

	ctx := context.Background()

	nvcfCfg := nvcfAPIKeysConfig(config, ownerOverride)
	nvctCfg := nvctAPIKeysConfig(config, ownerOverride)
	eventLedgerCfg := eventLedgerAPIKeysConfig(config, ownerOverride)
	nvcfClient := apikeys.NewClient(nvcfCfg)
	nvctClient := apikeys.NewClient(nvctCfg)
	eventLedgerClient := apikeys.NewClient(eventLedgerCfg)

	logging.Info("Fetching all API keys (function, task and event-ledger)...")

	functionKeys, err := nvcfClient.ListAPIKeys(ctx)
	if err != nil {
		return fmt.Errorf("failed to list function API keys: %w", err)
	}
	taskKeys, err := nvctClient.ListAPIKeys(ctx)
	if err != nil {
		return fmt.Errorf("failed to list task API keys: %w", err)
	}
	eventLedgerKeys, err := eventLedgerClient.ListAPIKeys(ctx)
	if err != nil {
		return fmt.Errorf("failed to list Event Ledger API keys: %w", err)
	}

	// Distinct owner IDs whose keys were actually found (an owner appears only
	// if it had keys; deduped when an override makes multiple issuers the same owner).
	ownerIds := []string{}
	seenOwner := map[string]bool{}
	addOwner := func(hasKeys bool, owner string) {
		if hasKeys && !seenOwner[owner] {
			seenOwner[owner] = true
			ownerIds = append(ownerIds, owner)
		}
	}
	addOwner(len(functionKeys) > 0, nvcfCfg.OwnerID)
	addOwner(len(taskKeys) > 0, nvctCfg.OwnerID)
	addOwner(len(eventLedgerKeys) > 0, eventLedgerCfg.OwnerID)

	total := len(functionKeys) + len(taskKeys) + len(eventLedgerKeys)
	if total == 0 {
		if IsJSONOutput() {
			return OutputJSON(map[string]interface{}{
				"ownerIds": ownerIds,
				"deleted":  0,
				"total":    0,
			})
		}
		logging.Info("No API keys found")
		return nil
	}

	logging.Info("Found %d API key(s) to delete (%d function, %d task, %d event-ledger)",
		total, len(functionKeys), len(taskKeys), len(eventLedgerKeys))

	// Interactive confirmation prompt unless --force is used
	if !clearForce {
		logging.Warning("Are you sure you want to delete ALL %d API key(s)?", total)
		logging.Plain("This action cannot be undone. All keys will be immediately invalidated.")
		logging.Plain("Keys to be deleted:")
		for _, key := range functionKeys {
			logging.Plain("  - %s (function) %s", key.ID, key.Description)
		}
		for _, key := range taskKeys {
			logging.Plain("  - %s (task) %s", key.ID, key.Description)
		}
		for _, key := range eventLedgerKeys {
			logging.Plain("  - %s (event-ledger) %s", key.ID, key.Description)
		}

		if !promptForConfirmation("Do you want to proceed?") {
			logging.Info("Bulk deletion cancelled by user")
			return nil
		}
	}

	// Delete each key through the client whose issuer matches its origin.
	deletedCount := deleteAllKeys(ctx, nvcfClient, functionKeys, "function")
	deletedCount += deleteAllKeys(ctx, nvctClient, taskKeys, "task")
	deletedCount += deleteAllKeys(ctx, eventLedgerClient, eventLedgerKeys, "event-ledger")

	// Clear the local API key from state only when clearing the current actor's
	// keys (no explicit owner override) and something was actually deleted.
	clearedLocal := false
	if ownerOverride == "" && deletedCount > 0 {
		if err := LoadStateForCurrentCommand(); err == nil {
			currentState := GetCurrentState()
			if hasSavedAPIKeys(currentState) {
				clearSavedAPIKeys(currentState)
				if err := SaveStateForCurrentCommand(); err != nil {
					logging.Warning("Failed to clear local API key from state: %v", err)
				} else {
					clearedLocal = true
				}
			}
		}
	}

	if IsJSONOutput() {
		return OutputJSON(map[string]interface{}{
			"ownerIds": ownerIds,
			"deleted":  deletedCount,
			"total":    total,
		})
	}

	logging.Success("Successfully deleted %d out of %d API key(s)", deletedCount, total)
	if clearedLocal {
		logging.Info("Cleared local API key from state since it may have been deleted")
	}

	return nil
}

// parseExtendedDuration parses duration strings with support for days (d) and weeks (w)
func parseExtendedDuration(s string) (time.Duration, error) {
	// First try Go's standard parser
	if d, err := time.ParseDuration(s); err == nil {
		return d, nil
	}

	// Handle days and weeks manually
	if len(s) < 2 {
		return 0, fmt.Errorf("invalid duration format")
	}

	unit := s[len(s)-1:]
	valueStr := s[:len(s)-1]

	switch unit {
	case "d":
		// Parse days
		days, err := strconv.Atoi(valueStr)
		if err != nil {
			return 0, fmt.Errorf("invalid number of days: %s", valueStr)
		}
		return time.Duration(days) * 24 * time.Hour, nil

	case "w":
		// Parse weeks
		weeks, err := strconv.Atoi(valueStr)
		if err != nil {
			return 0, fmt.Errorf("invalid number of weeks: %s", valueStr)
		}
		return time.Duration(weeks) * 7 * 24 * time.Hour, nil

	default:
		// Try Go's parser one more time and return its error
		return time.ParseDuration(s)
	}
}

// promptForConfirmation asks the user for yes/no confirmation
// Returns true if user confirms (y/yes), false otherwise
func promptForConfirmation(message string) bool {
	reader := bufio.NewReader(os.Stdin)

	fmt.Printf("%s (y/n): ", message)

	response, err := reader.ReadString('\n')
	if err != nil {
		return false
	}

	response = strings.ToLower(strings.TrimSpace(response))
	return response == "y" || response == "yes"
}
