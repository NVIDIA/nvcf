func runAPIKeyGenerate(cmd *cobra.Command, args []string) error {
	// Load state
	if err := LoadStateForCurrentCommand(); err != nil {
		logging.Warning("Could not load existing state: %v", err)
	}

	// Load configuration
	config, err := client.LoadConfig()
	if err != nil {
		return fmt.Errorf("failed to load configuration: %w", err)
	}

	// Parse expiration duration (with support for days/weeks)
	duration, err := parseExtendedDuration(apikeyExpiresIn)
	if err != nil {
		return fmt.Errorf("invalid expiration duration '%s': %w", apikeyExpiresIn, err)
	}

	expirationTime := time.Now().Add(duration)
	if !IsJSONOutput() {
		logging.Info("Generating API key...")
		logging.Info("Description: %s", apikeyDescription)
		logging.Info("Expires: %s", expirationTime.Format("2006-01-02 15:04:05 MST"))
	}

	if len(apikeyScopes) > 0 && apikeyFor == "" {
		return fmt.Errorf("--scopes requires --for to specify which service (function, task or event-ledger)")
	}

	sm := GetStateManagerForCurrentCommand()

	type generatedKey struct {
		Service         string   `json:"service"`
		Key             string   `json:"apiKey"`
		Scopes          []string `json:"scopes"`
		Validated       bool     `json:"validated"`
		ValidationError string   `json:"validationError,omitempty"`
	}
	var generated []generatedKey

	generateBoth := apikeyFor == "" || apikeyFor == "all"

	if generateBoth || apikeyFor == "function" {
		if !IsJSONOutput() {
			logging.Info("Generating function API key...")
		}
		functionScopes := apikeyScopes
		if apikeyFor != "function" {
			functionScopes = nil
		}
		functionKey, genErr := generateAPIKey(config, apikeyDescription, expirationTime, functionScopes)
		if genErr != nil {
			return fmt.Errorf("failed to generate function API key: %w", genErr)
		}
		if functionKey == "" {
			return fmt.Errorf("received empty function API key from generation service")
		}
		effectiveScopes := functionScopes
		if len(effectiveScopes) == 0 {
			effectiveScopes = apikeys.DefaultScopes()
		}
		currentState := sm.GetState()
		sm.SetTokens(currentState.Token, functionKey, currentState.TokenExpiration, expirationTime)
		generated = append(generated, generatedKey{Service: "function", Key: functionKey, Scopes: effectiveScopes})
		// Persist immediately so a later task-key failure cannot discard an
		// already-minted function key.
		if err := SaveStateForCurrentCommand(); err != nil {
			logging.Warning("Failed to save function API key to state: %v", err)
		}
	}

	if generateBoth || apikeyFor == "task" {
		if !IsJSONOutput() {
			logging.Info("Generating task API key...")
		}
		taskScopes := apikeyScopes
		if apikeyFor != "task" {
			taskScopes = nil
		}
		taskKey, genErr := generateNVCTAPIKey(config, apikeyDescription, expirationTime, taskScopes)
		if genErr != nil {
			return fmt.Errorf("failed to generate task API key: %w", genErr)
		}
		if taskKey == "" {
			return fmt.Errorf("received empty task API key from generation service")
		}
		effectiveScopes := taskScopes
		if len(effectiveScopes) == 0 {
			effectiveScopes = apikeys.DefaultNVCTScopes()
		}
		sm.SetNVCTAPIKey(taskKey, expirationTime)
		generated = append(generated, generatedKey{Service: "task", Key: taskKey, Scopes: effectiveScopes})
		if err := SaveStateForCurrentCommand(); err != nil {
			logging.Warning("Failed to save task API key to state: %v", err)
		}
	}

	if generateBoth || apikeyFor == "event-ledger" {
		if !IsJSONOutput() {
			logging.Info("Generating Event Ledger API key...")
		}
		eventLedgerScopes := apikeyScopes
		if apikeyFor != "event-ledger" {
			eventLedgerScopes = nil
		}
		eventLedgerKey, genErr := generateEventLedgerAPIKey(config, apikeyDescription, expirationTime, eventLedgerScopes)
		if genErr != nil {
			return fmt.Errorf("failed to generate Event Ledger API key: %w", genErr)
		}
		if eventLedgerKey == "" {
			return fmt.Errorf("received empty Event Ledger API key from generation service")
		}
		effectiveScopes := eventLedgerScopes
		if len(effectiveScopes) == 0 {
			effectiveScopes = apikeys.DefaultEventLedgerScopes()
		}
		sm.SetEventLedgerAPIKey(eventLedgerKey, expirationTime)
		generated = append(generated, generatedKey{Service: "event-ledger", Key: eventLedgerKey, Scopes: effectiveScopes})
		if err := SaveStateForCurrentCommand(); err != nil {
			logging.Warning("Failed to save Event Ledger API key to state: %v", err)
		}
	}

	if apikeyFor != "" && apikeyFor != "all" && apikeyFor != "function" && apikeyFor != "task" && apikeyFor != "event-ledger" {
		return fmt.Errorf("unknown --for value %q: must be function, task or event-ledger", apikeyFor)
	}

	if apikeyValidate {
		for i := range generated {
			g := &generated[i]
			if !IsJSONOutput() {
				logging.Info("Validating %s API key...", g.Service)
			}
			var verr error
			switch g.Service {
			case "task":
				verr = validateNVCTAPIKey(config, g.Key)
			case "event-ledger":
				verr = validateEventLedgerAPIKey(config, g.Key)
			default:
				verr = validateAPIKey(config, g.Key)
			}
			if verr != nil {
				g.ValidationError = verr.Error()
				if !IsJSONOutput() {
					logging.Warning("%s API key validation failed: %v", g.Service, verr)
				}
			} else {
				g.Validated = true
				if !IsJSONOutput() {
					logging.Success("%s API key validation passed!", g.Service)
				}
			}
		}
	}

	if IsJSONOutput() {
		return OutputJSON(map[string]interface{}{
			"description": apikeyDescription,
			"expiresAt":   expirationTime,
			"keys":        generated,
		})
	}

	logging.Success("API key(s) generated successfully!")
	for _, g := range generated {
		logging.Plain("%s key: %s", g.Service, g.Key)
	}
	logging.Plain("Expires: %s", expirationTime.Format("2006-01-02 15:04:05 MST"))

	return nil
}

// generateAPIKey generates an NVCF-scoped API key.
func generateAPIKey(config *client.Config, description string, expiresAt time.Time, customScopes []string) (string, error) {
	apiKeysConfig := &apikeys.Config{
		ServiceURL:    getConfigValueWithDefault("api_keys_service_url", "https://api-keys.nvcf.nvidia.com"),
		ServiceID:     getConfigValueWithDefault("API_KEYS_SERVICE_ID", "nvidia-cloud-functions-ncp-service-id-aketm"),
		IssuerService: getConfigValueWithDefault("API_KEYS_ISSUER_SERVICE", "nvcf-api"),
		OwnerID:       getConfigValueWithDefault("API_KEYS_OWNER_ID", "svc@nvcf-api.local"),
		JWTToken:      config.Token,
		HostHeader:    getConfigValueWithDefault("api_keys_host", ""),
		Debug:         config.Debug,
	}
	return apikeys.NewClient(apiKeysConfig).GenerateAPIKey(context.Background(), description, expiresAt, customScopes)
}

