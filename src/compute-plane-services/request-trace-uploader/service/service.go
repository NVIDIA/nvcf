// Package service runs the request-trace uploader: startup and recovery, the
// pipeline from closed segment to confirmed export and cleanup, and the health
// endpoints. Start with NewUploader.
package service

import (
	"net/http"
	"time"
)

func newHTTPServer(addr string, handler http.Handler) *http.Server {
	return &http.Server{
		Addr:              addr,
		Handler:           handler,
		ReadHeaderTimeout: 5 * time.Second,
		ReadTimeout:       15 * time.Second,
		WriteTimeout:      15 * time.Second,
		IdleTimeout:       60 * time.Second,
	}
}
