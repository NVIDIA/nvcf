package harness

import (
	"errors"
	"os"
	"os/exec"
	"syscall"
)

// configureCommandCancellation gives each BDD command its own process group.
// Context cancellation kills the group so make, kubectl, and shell descendants
// cannot outlive the step and mutate ledger-backed inputs after signal cleanup.
func configureCommandCancellation(cmd *exec.Cmd) {
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	cmd.Cancel = func() error {
		if cmd.Process == nil {
			return os.ErrProcessDone
		}
		err := syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL)
		if errors.Is(err, syscall.ESRCH) {
			return os.ErrProcessDone
		}
		return err
	}
}
