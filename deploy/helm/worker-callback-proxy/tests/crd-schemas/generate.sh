# Generates the kubeconform schemas for the CRD kinds this chart renders, from
# the CRD versions NVCF ships:
#   - cert-manager Certificate: the vendored cert-manager chart in this repo.
#   - Prometheus Operator ServiceMonitor: the prometheus-operator-crds release
#     pinned by the observability stack.
# Usage: generate.sh [OUT_DIR]. Needs helm, yq, curl and Docker (the converter
# needs PyYAML, so it runs in a pinned Python image).
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "${script_dir}/../../../../.." && pwd)"
out_dir="${1:-${script_dir}}"

kubeconform_version="v0.8.0"
converter_url="https://raw.githubusercontent.com/yannh/kubeconform/${kubeconform_version}/scripts/openapi2jsonschema.py"
converter_sha256="d145babfbb765004030764e1b4e518bfb7a4bd7f111691a08fa57983b81881f3"
python_image="python:3.13-slim@sha256:b3575dcf816cdacc5292df77a6e3e59b8941631078373a045efa2ac1e9c5c3b2"
pyyaml_version="6.0.2"

cert_manager_chart="${repo_root}/deploy/helm/cert-manager/charts/cert-manager"
cert_manager_version="$(yq -r .version "${cert_manager_chart}/Chart.yaml")"

observability_state="${repo_root}/deploy/stacks/observability/helmfile.d/01-observability.yaml.gotmpl"
prometheus_crds_repo="https://prometheus-community.github.io/helm-charts"
prometheus_crds_version="$(sed -nE 's/.*dig "prometheusOperatorCrds" "version" "([^"]+)".*/\1/p' "${observability_state}")"
[[ -n "${prometheus_crds_version}" ]] || {
  echo "cannot read the prometheus-operator-crds version from ${observability_state}" >&2
  exit 1
}

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT
mkdir -p "${work}/crds" "${work}/out"

helm template cert-manager "${cert_manager_chart}" --set crds.enabled=true \
  --show-only templates/crd-cert-manager.io_certificates.yaml >"${work}/crds/certificates.yaml"

helm pull prometheus-operator-crds --repo "${prometheus_crds_repo}" \
  --version "${prometheus_crds_version}" --untar --destination "${work}/chart"
helm template prometheus-operator-crds "${work}/chart/prometheus-operator-crds" |
  yq 'select(.metadata.name == "servicemonitors.monitoring.coreos.com")' >"${work}/crds/servicemonitors.yaml"

for crd in certificates servicemonitors; do
  [[ "$(yq -r .kind "${work}/crds/${crd}.yaml")" == "CustomResourceDefinition" ]] || {
    echo "no ${crd} CRD in its source" >&2
    exit 1
  }
done

curl -fsSL "${converter_url}" -o "${work}/openapi2jsonschema.py"
echo "${converter_sha256}  ${work}/openapi2jsonschema.py" | shasum -a 256 -c - >/dev/null

docker run --rm -v "${work}:/work" -w /work/out -e FILENAME_FORMAT='{fullgroup}_{kind}_{version}' \
  "${python_image}" sh -c "
    pip install --quiet --disable-pip-version-check --root-user-action=ignore PyYAML==${pyyaml_version} &&
    python /work/openapi2jsonschema.py /work/crds/certificates.yaml /work/crds/servicemonitors.yaml >/dev/null"
for group in cert-manager.io monitoring.coreos.com; do
  mkdir -p "${work}/out/${group}"
  for f in "${work}/out/${group}"_*.json; do
    mv "${f}" "${work}/out/${group}/$(basename "${f}" | sed "s/^${group}_//")"
  done
done

sha() { shasum -a 256 "$1" | cut -d' ' -f1; }
cat >"${work}/out/PROVENANCE.md" <<EOF
# CRD schema provenance

Generated by \`generate.sh\`; do not edit. Regenerate with
\`make crd-schemas\` after changing a source version, and check with
\`make verify-crd-schemas\`.

| Schema | Source | CRD sha256 |
| --- | --- | --- |
| \`cert-manager.io/certificate_v1.json\` | \`deploy/helm/cert-manager/charts/cert-manager\` ${cert_manager_version}, \`templates/crd-cert-manager.io_certificates.yaml\` | \`$(sha "${work}/crds/certificates.yaml")\` |
| \`monitoring.coreos.com/servicemonitor_v1.json\` | \`prometheus-operator-crds\` ${prometheus_crds_version} from ${prometheus_crds_repo}, the version pinned in \`deploy/stacks/observability/helmfile.d/01-observability.yaml.gotmpl\` | \`$(sha "${work}/crds/servicemonitors.yaml")\` |

Converter: kubeconform ${kubeconform_version} \`scripts/openapi2jsonschema.py\`
(sha256 \`${converter_sha256}\`), run with PyYAML ${pyyaml_version} in
\`${python_image}\`.
EOF

mkdir -p "${out_dir}"
for f in cert-manager.io/certificate_v1.json monitoring.coreos.com/servicemonitor_v1.json PROVENANCE.md; do
  mkdir -p "${out_dir}/$(dirname "${f}")"
  cp "${work}/out/${f}" "${out_dir}/${f}"
done
echo "wrote CRD schemas to ${out_dir}"
