# Every supported external authentication mode must pass validation and retain
# the external collector endpoint. Autoscaler-specific auth values are covered
# by the self-managed observability test.
external_backend_args=(
  --state-values-set=metricsBackend.mode=existing
  --state-values-set=metricsBackend.type=external
  --state-values-set-string=metricsBackend.remoteWriteEndpoint=https://metrics.example.com/write
  --state-values-set-string=metricsBackend.promqlEndpoint=https://metrics.example.com
)
auth_cases=(
  'none|-'
  'token|--state-values-set-string=metricsBackend.authentication.authnEndpoint=https://auth.example.com'
  'mtls|--state-values-set-string=metricsBackend.authentication.clientCertificatePath=/tls/client.crt --state-values-set-string=metricsBackend.authentication.clientPrivateKeyPath=/tls/client.key'
)

for row in "${auth_cases[@]}"; do
  IFS='|' read -r auth_mode arg_string <<<"$row"
  auth_args=()
  if [[ "$arg_string" != "-" ]]; then
    read -r -a auth_args <<<"$arg_string"
  fi
  case_args=(
    "${external_backend_args[@]}"
    --state-values-set="metricsBackend.authentication.mode=$auth_mode"
    "${auth_args[@]}"
  )

  expected_releases='default-monitors,opentelemetry-operator,otel-collector,prometheus-operator-crds'
  assert_equal "$(profile_releases_csv control "${case_args[@]}")" \
    "$expected_releases" "external $auth_mode release set"
  values_file="$work_dir/external-$auth_mode-collector-values.yaml"
  write_release_values control otel-collector "$values_file" \
    "${case_args[@]}"
  assert_yaml_value "$values_file" \
    '.config.exporters.prometheusremotewrite.endpoint' \
    'https://metrics.example.com/write' \
    "external $auth_mode remote-write endpoint"
done

