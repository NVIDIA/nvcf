  'target-and-rbac-disabled|control|default-monitors,opentelemetry-operator,otel-collector,prometheus-operator-crds,victoria-metrics|monitoring/opentelemetry-operator,monitoring/prometheus-operator-crds,monitoring/victoria-metrics|monitoring/prometheus-operator-crds|monitoring/prometheus-operator-crds|--state-values-set=observability.components.targetAllocator.mode=disabled --state-values-set=observability.components.discoveryRbac.mode=disabled|false|false'
  'rbac-existing|control|default-monitors,opentelemetry-operator,otel-collector,prometheus-operator-crds,victoria-metrics|monitoring/opentelemetry-operator,monitoring/prometheus-operator-crds,monitoring/victoria-metrics|monitoring/prometheus-operator-crds|monitoring/prometheus-operator-crds|--state-values-set=observability.components.discoveryRbac.mode=existing|true|false'
  'backend-existing|control|default-monitors,opentelemetry-operator,otel-collector,prometheus-operator-crds|monitoring/opentelemetry-operator,monitoring/prometheus-operator-crds|monitoring/prometheus-operator-crds|monitoring/prometheus-operator-crds|--state-values-set=metricsBackend.mode=existing --state-values-set=metricsBackend.type=external --state-values-set-string=metricsBackend.remoteWriteEndpoint=https://metrics.example.com/write --state-values-set-string=metricsBackend.promqlEndpoint=https://metrics.example.com|true|true'
