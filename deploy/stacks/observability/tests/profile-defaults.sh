  "default monitors chart ServiceMonitor template count"

pod_monitor_template_count="$(
  find "$stack_dir/charts/nvcf-default-monitors/templates" \
    -maxdepth 1 -type f -name '*podmonitor*.yaml' |
    wc -l |
    tr -d ' '
)"
assert_equal "$pod_monitor_template_count" "1" \
  "default monitors chart PodMonitor template count"

# Assert profile-derived release values with write-values. The disabled profile
# is covered by the empty release set in the golden matrix.
for profile in control compute all; do
  collector_values="$work_dir/$profile-collector-values.yaml"
  monitor_values="$work_dir/$profile-monitor-values.yaml"
  write_release_values "$profile" otel-collector "$collector_values"
  write_release_values "$profile" default-monitors "$monitor_values"

  assert_yaml_value "$collector_values" '.targetAllocator.enabled' true \
    "$profile targetAllocator.enabled"
  assert_yaml_value "$collector_values" '.targetAllocatorRbac.create' true \
    "$profile targetAllocatorRbac.create"
  assert_yaml_value "$collector_values" \
    '.config.exporters.prometheusremotewrite.endpoint' \
    'http://vmsingle.monitoring.svc.cluster.local:8428/api/v1/write' \
    "$profile bundled remote-write endpoint"

  case "$profile" in
    control)
      expected_control=true
      expected_compute=false
      ;;
    compute)
      expected_control=false
      expected_compute=true
      ;;
    all)
      expected_control=true
      expected_compute=true
      ;;
  esac
  assert_yaml_value "$monitor_values" '.controlPlane.enabled' \
    "$expected_control" "$profile control monitor group"
  assert_yaml_value "$monitor_values" '.computePlane.enabled' \
    "$expected_compute" "$profile compute monitor group"
done

