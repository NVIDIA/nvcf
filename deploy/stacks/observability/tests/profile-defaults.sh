  'operator-disabled|control|default-monitors,prometheus-operator-crds,victoria-metrics|absent|absent|monitoring/prometheus-operator-crds|--state-values-set=observability.components.otelOperator.mode=disabled --state-values-set=observability.components.collector.mode=disabled --state-values-set=observability.components.targetAllocator.mode=disabled --state-values-set=observability.components.discoveryRbac.mode=disabled|absent|absent'
)

for row in "${mode_cases[@]}"; do
  IFS='|' read -r case_name profile expected_releases collector_needs \
    operator_needs monitor_needs arg_string target_allocator_enabled \
    target_allocator_rbac_create <<<"$row"

  case_args=()
  if [[ "$arg_string" != "-" ]]; then
    read -r -a case_args <<<"$arg_string"
  fi

  actual_releases="$(profile_releases_csv "$profile" "${case_args[@]}")"
  assert_equal "$actual_releases" "$expected_releases" \
    "$case_name release set"
  assert_release_needs "$case_name" "$profile" otel-collector \
    "$collector_needs" "${case_args[@]}"
  assert_release_needs "$case_name" "$profile" opentelemetry-operator \
    "$operator_needs" "${case_args[@]}"
  assert_release_needs "$case_name" "$profile" default-monitors \
    "$monitor_needs" "${case_args[@]}"

  if [[ "$target_allocator_enabled" != "absent" ]]; then
    values_file="$work_dir/$case_name-collector-values.yaml"
    write_release_values "$profile" otel-collector "$values_file" \
      "${case_args[@]}"
    assert_yaml_value "$values_file" '.targetAllocator.enabled' \
      "$target_allocator_enabled" "$case_name targetAllocator.enabled"
    assert_yaml_value "$values_file" '.targetAllocatorRbac.create' \
      "$target_allocator_rbac_create" \
      "$case_name targetAllocatorRbac.create"
  fi
done

control_monitors="$(awk -F'|' '$1 == "control" {print $3}' "$golden_file")"
compute_monitors="$(awk -F'|' '$1 == "compute" {print $3}' "$golden_file")"
compute_without_worker="${compute_monitors/,PodMonitor\/nvcf-default-monitors-worker/}"

monitor_override_cases=(
  "control-groups-swapped|control|$compute_monitors|--state-values-set=defaultMonitors.controlPlane.enabled=false --state-values-set=defaultMonitors.computePlane.enabled=true"
  "compute-groups-swapped|compute|$control_monitors|--state-values-set=defaultMonitors.controlPlane.enabled=true --state-values-set=defaultMonitors.computePlane.enabled=false"
  "compute-worker-disabled|compute|$compute_without_worker|--state-values-set=defaultMonitors.computePlane.worker.enabled=false"
)

for row in "${monitor_override_cases[@]}"; do
  IFS='|' read -r case_name profile expected_monitors arg_string <<<"$row"
  read -r -a case_args <<<"$arg_string"
  render_monitors "$profile" "$case_name" "${case_args[@]}"
  actual_monitors="$(monitor_targets_csv "$work_dir/$case_name")"
  assert_equal "$actual_monitors" "$expected_monitors" \
    "$case_name rendered monitors"
done

