#!/usr/bin/env bash
set -euo pipefail

stack_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
golden_file="$stack_dir/tests/golden/profile-matrix.txt"
work_dir="$(mktemp -d)"
trap 'rm -rf "$work_dir"' EXIT

update_golden=false
case "${1:-}" in
  "") ;;
  --update-golden) update_golden=true ;;
  *)
    echo "usage: $0 [--update-golden]" >&2
    exit 2
    ;;
esac

fail() {
  echo "profile-defaults: $*" >&2
  exit 1
}

for command in helm helmfile yq; do
  command -v "$command" >/dev/null 2>&1 || fail "$command is required"
done

helmfile_args=(
  --file "$stack_dir/helmfile.d/01-observability.yaml.gotmpl"
  --environment default
  --allow-no-matching-release
)

profile_release_json() {
  local profile="$1"
  shift

  HELMFILE_ENV=local helmfile \
    "${helmfile_args[@]}" \
    --state-values-set "observability.profile=$profile" \
    "$@" \
    list --output json --skip-charts 2>/dev/null
}

profile_releases_csv() {
  local profile="$1"
  shift

  profile_release_json "$profile" "$@" |
    yq -p=json -o=yaml -r '.[].name' |
    sort -u |
    paste -sd, -
}

render_monitors() {
  local profile="$1"
  local output_name="$2"
  shift 2
  local output_dir="$work_dir/$output_name"

  mkdir -p "$output_dir"
  HELMFILE_ENV=local helmfile \
    "${helmfile_args[@]}" \
    --state-values-set "observability.profile=$profile" \
    "$@" \
    --selector name=default-monitors \
    template --output-dir "$output_dir" >/dev/null
}

monitor_targets_csv() {
  local output_dir="$1"
  local file

  {
    while IFS= read -r file; do
      yq -N -r \
        'select(.kind == "ServiceMonitor" or .kind == "PodMonitor") | .kind + "/" + .metadata.name' \
        "$file"
    done < <(find "$output_dir" -type f -name '*.yaml' -print | sort)
  } | sort -u | paste -sd, -
}

write_release_values() {
  local profile="$1"
  local release="$2"
  local output_file="$3"
  shift 3

  HELMFILE_ENV=local HELMFILE_CACHE_HOME="$work_dir/helmfile-cache" helmfile \
    "${helmfile_args[@]}" \
    --state-values-set "observability.profile=$profile" \
    "$@" \
    --selector "name=$release" \
    write-values --output-file-template "$output_file" >/dev/null
}

release_needs_csv() {
  local profile="$1"
  local release="$2"
  shift 2

  HELMFILE_ENV=local helmfile \
    "${helmfile_args[@]}" \
    --state-values-set "observability.profile=$profile" \
    "$@" \
    --selector "name=$release" \
    --chart "$stack_dir/charts/nvcf-otel-collector" \
    build 2>/dev/null |
    yq -r '.releases[]? | select(.name == "'"$release"'") | .needs[]?' |
    sort -u |
    paste -sd, -
}

assert_equal() {
  local actual="$1"
  local expected="$2"
  local description="$3"

  [[ "$actual" == "$expected" ]] ||
    fail "$description: expected '$expected', got '$actual'"
}

assert_yaml_value() {
  local file="$1"
  local expression="$2"
  local expected="$3"
  local description="$4"
  local actual

  actual="$(yq -r "$expression" "$file")"
  assert_equal "$actual" "$expected" "$description"
}

assert_release_needs() {
  local case_name="$1"
  local profile="$2"
  local release="$3"
  local expected="$4"
  shift 4

  if [[ "$expected" == "absent" ]]; then
    return
  fi
  if [[ "$expected" == "none" ]]; then
    expected=""
  fi

  local actual
  actual="$(release_needs_csv "$profile" "$release" "$@")"
  assert_equal "$actual" "$expected" "$case_name $release dependencies"
}

generate_profile_matrix() {
  local output_file="$1"
  local profile releases monitors

  {
    echo "# Generated by \`make generate-test-golden\`. Review changes before committing."
    echo '# profile|sorted release names|sorted rendered monitor resources'
    for profile in disabled control compute all; do
      releases="$(profile_releases_csv "$profile")"
      monitors=""
      if [[ "$profile" != "disabled" ]]; then
        render_monitors "$profile" "matrix-$profile"
        monitors="$(monitor_targets_csv "$work_dir/matrix-$profile")"
      fi
      printf '%s|%s|%s\n' "$profile" "$releases" "$monitors"
    done
  } >"$output_file"
}

actual_matrix="$work_dir/profile-matrix.txt"
generate_profile_matrix "$actual_matrix"

if [[ "$update_golden" == "true" ]]; then
  mkdir -p "$(dirname "$golden_file")"
  cp "$actual_matrix" "$golden_file"
  echo "profile-defaults: updated $golden_file"
  exit 0
fi

[[ -f "$golden_file" ]] || fail "missing golden fixture: $golden_file"
if ! diff -u "$golden_file" "$actual_matrix"; then
  fail "profile release or monitor matrix differs from the golden fixture"
fi

fixture_profiles="$(awk -F'|' '!/^#/ {print $1}' "$golden_file" | paste -sd, -)"
assert_equal "$fixture_profiles" "disabled,control,compute,all" \
  "golden profile rows"

service_monitor_template_count="$(
  find "$stack_dir/charts/nvcf-default-monitors/templates" \
    -maxdepth 1 -type f -name '*servicemonitor*.yaml' |
    wc -l |
    tr -d ' '
)"
