// helmPushTarget describes one NGC org the chart gets published to.
// Either NGCPath (hardcoded org/team path, e.g.
// "0651155215864979/ncp-dev") or NGCPathVar (the name of a CI
// variable that resolves to the path, e.g. "NGC_ORG_nv_ngc_devops")
// must be set; the generator validates exactly one is provided. The
// NGC key always comes from a CI variable name (NGCKeyVar) since
// the keys are protected secrets.
type helmPushTarget struct {
	// Name uniquely identifies this target within the service. Becomes
	// the suffix of the generated helm-push-<svc>-<name> job. Choose
	// short keys like "ncp-dev", "nv-ngc-devops", "nvcf-internal".
	Name string `yaml:"name"`
	// NGCPath is a literal org/team path on NGC, e.g.
	// "0651155215864979/ncp-dev". Mutually exclusive with NGCPathVar.
	NGCPath string `yaml:"ngc_path,omitempty"`
	// NGCPathVar is the name of a CI variable holding the NGC path
	// (e.g. "NGC_ORG_nv_ngc_devops"). The generator emits a `$VAR`
	// reference into the component input; resolution happens at
	// pipeline runtime. Mutually exclusive with NGCPath.
	NGCPathVar string `yaml:"ngc_path_var,omitempty"`
	// NGCKeyVar (legacy) is the name of a CI variable holding the NGC
	// API key (e.g. "NGC_DEVOPS_API_KEY"). The generator emits a
	// `$VAR` reference into the cds-component input. Optional; use
	// Auth instead for new entries. Mutually exclusive with Auth.
	NGCKeyVar string `yaml:"ngc_key_var,omitempty"`
	// Auth selects the credential source for this push target. Same
	// schema as releaseImagePushAuth (ci_var | vault | vault_ncp_dev).
	// vault_ncp_dev is the umbrella's standard for ncp-dev pushes
	// (matches the image-push auth pattern for ncp-dev). When set,
	// NGCKeyVar must be empty. Optional for backwards compatibility;
	// new entries should set Auth.
	Auth *releaseImagePushAuth `yaml:"auth,omitempty"`
	// ClassicRegistry, when true, ALSO publishes the chart to NGC's
	// classic chart registry (https://helm.ngc.nvidia.com/<ngc_path>/)
	// via the cds-components/helm-push-ngc component, in addition to
	// the OCI push (oci://nvcr.io/<ngc_path>). The two surfaces do not
	// share an index: an OCI push does not populate the classic
	// chart-registry index. Set this for charts whose consumers pull
	// via `helm pull --repo https://helm.ngc.nvidia.com/...` (e.g. some
	// Argo Applications). Requires ci_var / NGCKeyVar auth (the classic
	// push uses the NGC CLI, which the cds-component image supplies).
	ClassicRegistry bool `yaml:"classic_registry,omitempty"`
}

// releaseImagePushTarget describes one registry the image gets pushed
// to. Each target has its own Bazel push target (declared in the
// service's nvidia-internal/destinations.bzl) and its own auth source.
type releaseImagePushTarget struct {
	Name        string               `yaml:"name"`
	BazelTarget string               `yaml:"bazel_target"`
	Auth        releaseImagePushAuth `yaml:"auth"`
	// DockerAuthPath, if set, is written as the key in
	// ~/.docker/config.json instead of the bare registry host. Use
	// when the service's base image lives on the same registry as the
	// push target (e.g. Rust services that pull `nvcr.io/nvidia/
	// distroless/cc` while pushing to `nvcr.io/<org>/<image>`).
	// rules_oci does longest-prefix matching on the auth keys; if the
	// scoped token's key is just "nvcr.io" it gets applied to every
	// nvcr.io pull including the public distroless base, and the
	// token's scoped permissions 403 the public read.
	//
	// Format: full path without scheme, e.g.
	//   `nvcr.io/ema5hzr4ziav/nvcf_autoscaling`
	//   `nvcr.io/0651155215864979/ncp-dev/nvcf-function-autoscaler`
	//
	// Optional. Empty falls back to the host-only key (works for
	// services whose base image isn't on the same registry).
	DockerAuthPath string `yaml:"docker_auth_path,omitempty"`
}

// releaseImagePushAuth holds the credential source for one push
// target. Three auth types are supported:
//
//   - `type: vault` (per-service vault key) fetches NGC_REGISTRY +
//     NGC_REGISTRY_TOKEN from kv/gitlab/ngc-registry-auth/<vault_key>.
//     Used for legacy NGC tenants where each upstream project had
//     its own vault entry (e.g. nvcr.io/nvidian/kaze for grpc-proxy,
//     nvcr.io/ema5hzr4ziav for rs-autoscaler).
//
//   - `type: vault_ncp_dev` (shared ncp-dev SERVICE_KEY) fetches
//     NGC_KEY from kv/app/ncp/ngc-key and exposes it as
//     NVCR_0651155215864979_NCP_DEV_SERVICE_KEY_RW. This is the
//     umbrella's standard auth for the ncp-dev tenant
//     (nvcr.io/0651155215864979/ncp-dev/*). Same secret the NCP team
//     owns and rotates; same path the ncp-service-helm-release
//     cds-component uses. No per-service VaultKey or CIVar needed.
//
//   - `type: ci_var` uses the named GitLab CI/CD variable directly
//     (typically set at the nvcf group level). Reserved for the few
//     remaining cases that cannot use vault auth.
type releaseImagePushAuth struct {
	Type     string `yaml:"type"`
	VaultKey string `yaml:"vault_key,omitempty"`
	CIVar    string `yaml:"ci_var,omitempty"`
}

