func main() {
	if err := run(os.Args[1:], os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(argv []string, stdout *os.File) error {
	parsed, err := parseArgs(argv)
	if err != nil {
		return err
	}

	cfg, err := loadConfig(parsed.ConfigPath)
	if err != nil {
		return err
	}

	if parsed.GoWorkOutputPath != "" {
		renderedGoWork, err := renderGoWork(cfg, parsed.ConfigPath)
		if err != nil {
			return err
		}
		if err := os.WriteFile(parsed.GoWorkOutputPath, []byte(renderedGoWork), 0o644); err != nil {
			return err
		}
	}

	if parsed.ReleaseOutputPath != "" {
		renderedRelease, err := renderReleasePipeline(cfg, parsed.ConfigPath)
		if err != nil {
			return err
		}
		if err := os.WriteFile(parsed.ReleaseOutputPath, []byte(renderedRelease), 0o644); err != nil {
			return err
		}
	}

	if parsed.GitHubReleaseOutputPath != "" {
		renderedGitHubRelease, err := renderGitHubReleaseMetadata(cfg, parsed.ConfigPath)
		if err != nil {
			return err
		}
		if err := os.WriteFile(parsed.GitHubReleaseOutputPath, renderedGitHubRelease, 0o644); err != nil {
			return err
		}
	}

	if parsed.OutputPath == "" {
		// Only a non-default output path was requested (go-work
		// and/or release-output); skip the default child-pipeline
		// stdout dump.
		if parsed.GoWorkOutputPath != "" || parsed.ReleaseOutputPath != "" || parsed.GitHubReleaseOutputPath != "" {
			return nil
		}
	}

	rendered, err := renderPipeline(cfg, parsed.ConfigPath)
	if err != nil {
		return err
	}

	if parsed.OutputPath == "" {
		_, err = stdout.WriteString(rendered)
		return err
	}

	return os.WriteFile(parsed.OutputPath, []byte(rendered), 0o644)
}

func parseArgs(argv []string) (args, error) {
	fs := flag.NewFlagSet("generate-subproject-ci", flag.ContinueOnError)
	fs.SetOutput(os.Stderr)

	parsed := args{
		ConfigPath: "tools/ci/subproject-validations.yaml",
	}
	fs.StringVar(&parsed.ConfigPath, "config", parsed.ConfigPath, "path to subproject validation config")
	fs.StringVar(&parsed.OutputPath, "output", "", "path to write generated child pipeline yaml")
	fs.StringVar(&parsed.GoWorkOutputPath, "go-work-output", "", "path to write generated go.work")
	fs.StringVar(&parsed.ReleaseOutputPath, "release-output", "", "path to write generated release-pipeline yaml")
	fs.StringVar(&parsed.GitHubReleaseOutputPath, "github-release-output", "", "path to write public GitHub release metadata json")

	if err := fs.Parse(argv); err != nil {
		return args{}, err
	}
	if fs.NArg() != 0 {
		return args{}, fmt.Errorf("unexpected arguments: %s", strings.Join(fs.Args(), " "))
	}
	return parsed, nil
}

func loadConfig(path string) (configFile, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return configFile{}, err
	}

	var cfg configFile
	if err := yaml.Unmarshal(raw, &cfg); err != nil {
		return configFile{}, err
	}
	if err := validateConfig(cfg); err != nil {
		return configFile{}, err
	}
	return cfg, nil
}

func validateConfig(cfg configFile) error {
	if cfg.Version != 1 {
		return fmt.Errorf("unsupported config version %d", cfg.Version)
	}
	if len(cfg.DefaultTags) == 0 {
		return errors.New("default_tags must not be empty")
	}
	// `profiles` may be empty when every subproject is release-only
	// (no validation jobs). Per-subproject validation below catches
	// references to undeclared profile names.
	if cfg.GoWork != nil {
		if strings.TrimSpace(cfg.GoWork.Go) == "" {
			return errors.New("go_work.go must not be empty")
		}
	}

	seenSubprojects := map[string]struct{}{}
	for _, subproject := range cfg.Subprojects {
		if strings.TrimSpace(subproject.ID) == "" {
			return errors.New("subproject id must not be empty")
		}
		if _, exists := seenSubprojects[subproject.ID]; exists {
			return fmt.Errorf("duplicate subproject id %q", subproject.ID)
		}
		seenSubprojects[subproject.ID] = struct{}{}
		if strings.TrimSpace(subproject.Path) == "" {
			return fmt.Errorf("subproject %q path must not be empty", subproject.ID)
		}
		if subproject.GoWork && cfg.GoWork == nil {
			return fmt.Errorf("subproject %q sets go_work but config does not define top-level go_work settings", subproject.ID)
		}
		// A subproject must declare at least one of `profile` (for the
		// child-pipeline validation jobs), `bazel` (for native subtree
		// Bazel build/test validation), or `release` (for the
		// release-pipeline auto-version + image-push jobs). These are
		// orthogonal: a service can validate via profile and/or Bazel
		// and also opt into auto-released images.
		hasProfile := strings.TrimSpace(subproject.Profile) != ""
		hasBazel := subproject.Bazel != nil
		hasRelease := subproject.Release != nil
		hasChecks := len(subproject.Checks) > 0
		hasHelmValidate := subproject.HelmValidate != nil
		if !hasProfile && !hasBazel && !hasRelease && !hasChecks && !hasHelmValidate {
			return fmt.Errorf("subproject %q must set profile, bazel, release, checks, or helm_validate", subproject.ID)
		}
		if hasProfile {
			profile, ok := cfg.Profiles[subproject.Profile]
			if !ok {
				return fmt.Errorf("subproject %q references unknown profile %q", subproject.ID, subproject.Profile)
			}
			if strings.TrimSpace(profile.Image) == "" {
				return fmt.Errorf("profile %q image must not be empty", subproject.Profile)
			}
			if len(profile.Checks) == 0 {
				return fmt.Errorf("profile %q must define at least one check", subproject.Profile)
			}
			for _, chk := range profile.Checks {
				if err := validateCheck(subproject.Profile, chk); err != nil {
					return err
				}
			}
		}
		if hasBazel {
			for _, target := range subproject.Bazel.Targets {
				trimmed := strings.TrimSpace(target)
				if trimmed == "" {
					return fmt.Errorf("subproject %q bazel.targets must not contain empty entries", subproject.ID)
				}
				if strings.ContainsAny(trimmed, " \t\r\n") {
					return fmt.Errorf("subproject %q bazel target %q must not contain whitespace", subproject.ID, target)
				}
			}
			for _, target := range subproject.Bazel.ExtraBuildTargets {
				trimmed := strings.TrimSpace(target)
				if trimmed == "" {
					return fmt.Errorf("subproject %q bazel.extra_build_targets must not contain empty entries", subproject.ID)
				}
				if strings.ContainsAny(trimmed, " \t\r\n") {
					return fmt.Errorf("subproject %q bazel extra build target %q must not contain whitespace", subproject.ID, target)
				}
			}
		}
		for _, chk := range subproject.Checks {
			if err := validateCheck(subproject.ID, chk); err != nil {
				return err
			}
		}
		if hasHelmValidate {
			if _, err := helmValidateChartPath(subproject); err != nil {
				return err
			}
		}
		if hasRelease {
			if err := validateRelease(subproject); err != nil {
				return err
			}
		}
	}
	return nil
}

func validateRelease(sp subproject) error {
	id := sp.ID
	rel := sp.Release
	if strings.TrimSpace(rel.ServiceName) == "" {
		return fmt.Errorf("subproject %q release.service_name must not be empty", id)
	}
	if tagFormat := strings.TrimSpace(rel.TagFormat); tagFormat != "" {
		tagFormat = filepath.ToSlash(tagFormat)
		if strings.ContainsAny(tagFormat, " \t\r\n") {
			return fmt.Errorf("subproject %q release.tag_format must not contain whitespace", id)
		}
		if strings.Count(tagFormat, releaseVersionPlaceholder) != 1 || !strings.HasSuffix(tagFormat, releaseVersionPlaceholder) {
			return fmt.Errorf("subproject %q release.tag_format must end with exactly one %s placeholder", id, releaseVersionPlaceholder)
		}
		prefix := releaseTagPrefix(tagFormat)
		if prefix == "" {
			return fmt.Errorf("subproject %q release.tag_format must have a non-empty prefix before %s", id, releaseVersionPlaceholder)
		}
		if path.IsAbs(prefix) || strings.HasPrefix(prefix, "refs/") {
			return fmt.Errorf("subproject %q release.tag_format must be a relative tag name, not %q", id, tagFormat)
		}
	}
	if legacyPrefix := strings.TrimSpace(rel.LegacyTagPrefix); legacyPrefix != "" {
		legacyPrefix = filepath.ToSlash(legacyPrefix)
		if strings.ContainsAny(legacyPrefix, " \t\r\n") {
			return fmt.Errorf("subproject %q release.legacy_tag_prefix must not contain whitespace", id)
		}
		if strings.Contains(legacyPrefix, releaseVersionPlaceholder) {
			return fmt.Errorf("subproject %q release.legacy_tag_prefix must be a static prefix without %s", id, releaseVersionPlaceholder)
		}
		if path.IsAbs(legacyPrefix) || strings.HasPrefix(legacyPrefix, "refs/") {
			return fmt.Errorf("subproject %q release.legacy_tag_prefix must be a relative tag prefix, not %q", id, legacyPrefix)
		}
		if legacyPrefix == releaseTagPrefix(releaseTagFormat(rel, releasePathForSubproject(sp))) {
			return fmt.Errorf("subproject %q release.legacy_tag_prefix must differ from the current release tag prefix", id)
		}
	}
	if len(rel.ImagePushTargets) == 0 && rel.Staging == nil && rel.Helm == nil && rel.Dockerfile == nil && rel.InternalRelease == nil && rel.ArchiveRelease == nil {
		return fmt.Errorf("subproject %q release must declare at least one of image_push_targets, staging, helm, dockerfile, internal_release, or archive_release", id)
	}
	// `image_push_targets` (Bazel oci_push) and `dockerfile` (buildah)
	// describe the same lane via different build systems; allowing
	// both would create two `<svc>-image-push` jobs.
	if len(rel.ImagePushTargets) > 0 && rel.Dockerfile != nil {
		return fmt.Errorf("subproject %q release cannot declare both image_push_targets and dockerfile", id)
	}
	if len(rel.ImagePushTargets) > 0 && rel.Staging != nil {
		return fmt.Errorf("subproject %q release cannot declare both image_push_targets and staging", id)
	}
	if rel.Staging != nil && rel.Dockerfile != nil {
		return fmt.Errorf("subproject %q release cannot declare both staging and dockerfile", id)
	}
	if rel.InternalRelease != nil {
		if len(rel.ImagePushTargets) > 0 || rel.Staging != nil || rel.Helm != nil || rel.Dockerfile != nil || rel.ArchiveRelease != nil {
			return fmt.Errorf("subproject %q release.internal_release is mutually exclusive with image_push_targets, staging, helm, dockerfile, and archive_release", id)
		}
	}
	// archive_release is a tag-only release shape; pairing it with any
	// build-and-push shape would emit two release lanes for the same
	// subproject.
	if rel.ArchiveRelease != nil {
		if len(rel.ImagePushTargets) > 0 || rel.Staging != nil || rel.Helm != nil || rel.Dockerfile != nil {
			return fmt.Errorf("subproject %q release.archive_release is mutually exclusive with image_push_targets, staging, helm, and dockerfile", id)
		}
		if subtree := strings.TrimSpace(rel.ArchiveRelease.Subtree); subtree != "" {
			subtree = filepath.ToSlash(subtree)
			if path.IsAbs(subtree) || subtree == ".." || strings.HasPrefix(subtree, "../") || strings.Contains(subtree, "/../") {
				return fmt.Errorf("subproject %q release.archive_release.subtree must be a clean relative path", id)
			}
		}
	}
	if versionFile := strings.TrimSpace(rel.VersionFile); versionFile != "" {
		versionFile = filepath.ToSlash(versionFile)
		if path.IsAbs(versionFile) || versionFile == ".." || strings.HasPrefix(versionFile, "../") || strings.Contains(versionFile, "/../") {
			return fmt.Errorf("subproject %q release.version_file must be relative to the service subtree", id)
		}
	}
	if sourceFile := strings.TrimSpace(rel.VersionMajorMinorSourceFile); sourceFile != "" {
		sourceFile = filepath.ToSlash(sourceFile)
		if strings.TrimSpace(rel.VersionFile) == "" {
			return fmt.Errorf("subproject %q release.version_major_minor_source_file requires release.version_file", id)
		}
		if path.IsAbs(sourceFile) || sourceFile == ".." || strings.HasPrefix(sourceFile, "../") || strings.Contains(sourceFile, "/../") {
			return fmt.Errorf("subproject %q release.version_major_minor_source_file must be relative to the service subtree", id)
		}
	}
	if rel.DevPrerelease {
		if strings.TrimSpace(rel.VersionFile) == "" {
			return fmt.Errorf("subproject %q release.dev_prerelease requires release.version_file", id)
		}
	}
	if rel.Dockerfile != nil {
		hasName := strings.TrimSpace(rel.Dockerfile.ImageName) != ""
		hasImages := len(rel.Dockerfile.Images) > 0
		if hasName == hasImages {
			return fmt.Errorf("subproject %q release.dockerfile must set exactly one of image_name or images", id)
		}
		if hasImages {
			seen := map[string]struct{}{}
			for _, im := range rel.Dockerfile.Images {
				if strings.TrimSpace(im.Name) == "" {
					return fmt.Errorf("subproject %q release.dockerfile.images[].name must not be empty", id)
				}
				if strings.TrimSpace(im.Target) == "" {
					return fmt.Errorf("subproject %q release.dockerfile.images[%q].target must not be empty", id, im.Name)
				}
				if _, dup := seen[im.Name]; dup {
					return fmt.Errorf("subproject %q release.dockerfile.images has duplicate name %q", id, im.Name)
				}
				seen[im.Name] = struct{}{}
			}
		}
	}
	if rel.Staging != nil {
		if len(rel.Staging.Images) == 0 {
			return fmt.Errorf("subproject %q release.staging.images must not be empty", id)
		}
		seenImages := map[string]struct{}{}
		for _, image := range rel.Staging.Images {
			if strings.TrimSpace(image.Name) == "" {
				return fmt.Errorf("subproject %q has release.staging.images entry with empty name", id)
			}
			if _, dup := seenImages[image.Name]; dup {
				return fmt.Errorf("subproject %q has duplicate release.staging.images entry %q", id, image.Name)
			}
			seenImages[image.Name] = struct{}{}
			if strings.TrimSpace(image.BazelImageTarget) == "" {
				return fmt.Errorf("subproject %q release.staging image %q bazel_image_target must not be empty", id, image.Name)
			}
			for i, mt := range image.MrPushTargets {
				if strings.TrimSpace(mt.Repository) == "" {
					return fmt.Errorf("subproject %q release.staging image %q mr_push_targets[%d] repository must not be empty", id, image.Name, i)
				}
				switch mt.Auth.Type {
				case "vault":
					if strings.TrimSpace(mt.Auth.VaultKey) == "" {
						return fmt.Errorf("subproject %q release.staging image %q mr_push_targets[%d] vault auth requires vault_key", id, image.Name, i)
					}
				case "vault_ncp_dev":
					// no extra fields required
				default:
					return fmt.Errorf("subproject %q release.staging image %q mr_push_targets[%d] auth type %q unsupported (use vault or vault_ncp_dev)", id, image.Name, i, mt.Auth.Type)
				}
			}
		}
	}
	seenTargets := map[string]struct{}{}
	for _, t := range rel.ImagePushTargets {
		if strings.TrimSpace(t.Name) == "" {
			return fmt.Errorf("subproject %q has release.image_push_targets entry with empty name", id)
		}
		if _, dup := seenTargets[t.Name]; dup {
			return fmt.Errorf("subproject %q has duplicate release.image_push_targets entry %q", id, t.Name)
		}
		seenTargets[t.Name] = struct{}{}
		if strings.TrimSpace(t.BazelTarget) == "" {
			return fmt.Errorf("subproject %q release target %q bazel_target must not be empty", id, t.Name)
		}
		switch t.Auth.Type {
		case "vault":
			if strings.TrimSpace(t.Auth.VaultKey) == "" {
				return fmt.Errorf("subproject %q release target %q vault auth requires vault_key", id, t.Name)
			}
		case "ci_var":
			if strings.TrimSpace(t.Auth.CIVar) == "" {
				return fmt.Errorf("subproject %q release target %q ci_var auth requires ci_var", id, t.Name)
			}
		case "vault_ncp_dev":
			// vault_ncp_dev hardcodes the vault path and env var
			// (kv/app/ncp/ngc-key -> NVCR_0651155215864979_NCP_DEV_SERVICE_KEY_RW),
			// so vault_key and ci_var must NOT be set (would be
			// misleading). The generator emits the same vault fetch
			// for any image-push or helm-push target using this auth
			// type.
			if strings.TrimSpace(t.Auth.VaultKey) != "" || strings.TrimSpace(t.Auth.CIVar) != "" {
				return fmt.Errorf("subproject %q release target %q vault_ncp_dev auth must not set vault_key or ci_var (path is hardcoded)", id, t.Name)
			}
		default:
			return fmt.Errorf("subproject %q release target %q has unsupported auth type %q (want \"vault\", \"ci_var\", or \"vault_ncp_dev\")", id, t.Name, t.Auth.Type)
		}
	}
	if rel.Helm != nil {
		if strings.TrimSpace(rel.Helm.ChartPath) == "" {
			return fmt.Errorf("subproject %q release.helm.chart_path must not be empty", id)
		}
		if len(rel.Helm.PushTargets) == 0 {
			return fmt.Errorf("subproject %q release.helm.push_targets must not be empty", id)
		}
		seenHelm := map[string]struct{}{}
		for _, t := range rel.Helm.PushTargets {
			if strings.TrimSpace(t.Name) == "" {
				return fmt.Errorf("subproject %q has release.helm.push_targets entry with empty name", id)
			}
			if _, dup := seenHelm[t.Name]; dup {
				return fmt.Errorf("subproject %q has duplicate release.helm.push_targets entry %q", id, t.Name)
			}
			seenHelm[t.Name] = struct{}{}
			hasLiteral := strings.TrimSpace(t.NGCPath) != ""
			hasVar := strings.TrimSpace(t.NGCPathVar) != ""
			if hasLiteral == hasVar {
				return fmt.Errorf("subproject %q helm push_target %q must set exactly one of ngc_path or ngc_path_var", id, t.Name)
			}
			// Auth resolution: exactly one of Auth or NGCKeyVar must
			// be set. New entries should use Auth; NGCKeyVar is the
			// legacy form (treated as type: ci_var by the generator).
			hasAuth := t.Auth != nil
			hasKeyVar := strings.TrimSpace(t.NGCKeyVar) != ""
			if hasAuth == hasKeyVar {
				return fmt.Errorf("subproject %q helm push_target %q must set exactly one of auth or ngc_key_var", id, t.Name)
			}
			if hasAuth {
				switch t.Auth.Type {
				case "ci_var":
					if strings.TrimSpace(t.Auth.CIVar) == "" {
						return fmt.Errorf("subproject %q helm push_target %q ci_var auth requires ci_var", id, t.Name)
					}
				case "vault_ncp_dev":
					if strings.TrimSpace(t.Auth.VaultKey) != "" || strings.TrimSpace(t.Auth.CIVar) != "" {
						return fmt.Errorf("subproject %q helm push_target %q vault_ncp_dev auth must not set vault_key or ci_var (path is hardcoded)", id, t.Name)
					}
				default:
					return fmt.Errorf("subproject %q helm push_target %q has unsupported auth type %q (want \"ci_var\" or \"vault_ncp_dev\")", id, t.Name, t.Auth.Type)
				}
			}
		}
	}
	return nil
}

func validateCheck(profileName string, chk check) error {
	if strings.TrimSpace(chk.ID) == "" {
		return fmt.Errorf("profile %q has check with empty id", profileName)
	}
	switch chk.Type {
	case "go-vendor":
		return nil
	case "go-codegen":
		if strings.TrimSpace(chk.Command) == "" {
			return fmt.Errorf("profile %q check %q must set command", profileName, chk.ID)
		}
		return nil
	case "go-unit-tests":
		return nil
	case "shell":
		if strings.TrimSpace(chk.Command) == "" {
			return fmt.Errorf("profile %q check %q must set command", profileName, chk.ID)
		}
		return nil
	case "go-workspace-shell":
		if strings.TrimSpace(chk.Command) == "" {
			return fmt.Errorf("profile %q check %q must set command", profileName, chk.ID)
		}
		return nil
	default:
		return fmt.Errorf("profile %q check %q uses unsupported type %q", profileName, chk.ID, chk.Type)
	}
}

func renderPipeline(cfg configFile, configPath string) (string, error) {
	pipeline := generatedPipeline{
		ConfigPath:  configPath,
		DefaultTags: cfg.DefaultTags,
	}

	for _, subproject := range cfg.Subprojects {
		if strings.TrimSpace(subproject.Profile) != "" {
			profile := cfg.Profiles[subproject.Profile]
			if strings.TrimSpace(profile.Extends) == ".bazel-check" {
				pipeline.HasBazelJobs = true
			}
			for _, chk := range profile.Checks {
				job, err := buildJob(cfg.SharedChangePaths, profile, subproject, chk)
				if err != nil {
					return "", err
				}
				pipeline.Jobs = append(pipeline.Jobs, job)
			}
		}

		if len(subproject.Checks) > 0 {
			checkProfile := profile{
				Stage: "validate",
				Image: "alpine:3.20",
			}
			for _, chk := range subproject.Checks {
				job, err := buildJob(cfg.SharedChangePaths, checkProfile, subproject, chk)
				if err != nil {
					return "", err
				}
				pipeline.Jobs = append(pipeline.Jobs, job)
			}
		}

		if subproject.HelmValidate != nil {
			job, err := buildHelmValidateJob(cfg.SharedChangePaths, subproject)
			if err != nil {
				return "", err
			}
			pipeline.Jobs = append(pipeline.Jobs, job)
		}

		if subproject.Bazel != nil {
			job := buildBazelJob(cfg.BazelSharedChangePaths, subproject)
			pipeline.HasBazelJobs = true
			pipeline.Jobs = append(pipeline.Jobs, job)
		}

	}

	// GitLab fails a triggered child pipeline that ends up with zero jobs (for
	// example, when a change only touches files not listed in any job's
	// `changes:` rule, like a docs-only MR). Emit an unconditional sentinel so
	// the child pipeline always has at least one job to run.
	pipeline.Jobs = append(pipeline.Jobs, generatedJob{
		Name:      "subproject-validations-sentinel",
		Stage:     "validate",
		Image:     "golang:1.26-bookworm",
		AlwaysRun: true,
		Script:    []string{"echo 'subproject-validations: no path-gated jobs matched this change set.'"},
	})

	tmpl, err := template.New("pipeline").Funcs(template.FuncMap{
		"yamlValue":    yamlScalar,
		"yamlListItem": yamlListItem,
	}).Parse(pipelineTemplate)
	if err != nil {
		return "", err
	}

	view := struct {
		ConfigPath   string
		DefaultTags  []string
		HasBazelJobs bool
		Jobs         []generatedJobView
	}{
		ConfigPath:   pipeline.ConfigPath,
		DefaultTags:  pipeline.DefaultTags,
		HasBazelJobs: pipeline.HasBazelJobs,
		Jobs:         make([]generatedJobView, 0, len(pipeline.Jobs)),
	}
	for _, job := range pipeline.Jobs {
		view.Jobs = append(view.Jobs, generatedJobView{
			Name:               job.Name,
			Stage:              job.Stage,
			Image:              job.Image,
			Extends:            job.Extends,
			Tags:               job.Tags,
			Services:           job.Services,
			Variables:          job.Variables,
			VariablePairs:      sortMap(job.Variables),
			Changes:            job.Changes,
			AlwaysRun:          job.AlwaysRun,
			SkipGlobalTriggers: job.SkipGlobalTriggers,
			Script:             job.Script,
			Coverage:           job.Coverage,
			Artifacts:          job.Artifacts,
		})
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, view); err != nil {
		return "", err
	}
	return buf.String(), nil
}

// defaultReleaseGeneratedPaths is the fallback set of generated /
// mechanical basenames used by the release-worthiness guard when
// configFile.ReleaseGeneratedPaths is unset. Keep in sync with the
// release_generated_paths comment in subproject-validations.yaml.
var defaultReleaseGeneratedPaths = []string{"MODULE.bazel.lock", ".oss-allowlist"}

func releaseGeneratedPaths(paths []string) []string {
	if len(paths) == 0 {
		paths = defaultReleaseGeneratedPaths
	}
	return append([]string(nil), paths...)
}

// generatedPathsRegex builds the `grep -E` alternation the guard uses to
// match generated/mechanical files, anchored to a basename at the start
// of the path or after a slash, e.g.
// `(^|/)(MODULE\.bazel\.lock|\.oss-allowlist)$`. Regex metacharacters in
// each entry are escaped so plain filenames work as written.
func generatedPathsRegex(paths []string) string {
	paths = releaseGeneratedPaths(paths)
	escaped := make([]string, 0, len(paths))
	for _, p := range paths {
		escaped = append(escaped, regexp.QuoteMeta(p))
	}
	return "(^|/)(" + strings.Join(escaped, "|") + ")$"
}

func releasePathForSubproject(sp subproject) string {
	releasePath := sp.Path
	if sp.Release != nil && sp.Release.ArchiveRelease != nil {
		if subtree := strings.TrimSpace(sp.Release.ArchiveRelease.Subtree); subtree != "" {
			releasePath = filepath.ToSlash(subtree)
		}
	}
	return filepath.ToSlash(releasePath)
}

const releaseVersionPlaceholder = "${version}"

func defaultReleaseTagFormat(releasePath string) string {
	prefix := strings.Trim(filepath.ToSlash(strings.TrimSpace(releasePath)), "/")
	if prefix == "" || prefix == "." {
		return "v" + releaseVersionPlaceholder
	}
	return prefix + "/v" + releaseVersionPlaceholder
}

func releaseTagFormat(rel *releaseConfig, releasePath string) string {
	if rel == nil {
		return ""
	}
	if tagFormat := strings.TrimSpace(rel.TagFormat); tagFormat != "" {
		return filepath.ToSlash(tagFormat)
	}
	return defaultReleaseTagFormat(releasePath)
}

func releaseTagPrefix(tagFormat string) string {
	return strings.TrimSuffix(tagFormat, releaseVersionPlaceholder)
}

func legacyTagPrefix(rel *releaseConfig) string {
	if rel == nil {
		return ""
	}
	return filepath.ToSlash(strings.TrimSpace(rel.LegacyTagPrefix))
}

func releaseTagRuleRegex(prefixes ...string) string {
	var parts []string
	seen := map[string]struct{}{}
	for _, prefix := range prefixes {
		prefix = strings.TrimSpace(prefix)
		if prefix == "" {
			continue
		}
		if _, ok := seen[prefix]; ok {
			continue
		}
		seen[prefix] = struct{}{}
		quoted := regexp.QuoteMeta(prefix)
		parts = append(parts, strings.ReplaceAll(quoted, "/", `\/`))
	}
	if len(parts) == 0 {
		return ""
	}
	if len(parts) == 1 {
		return parts[0]
	}
	return "(" + strings.Join(parts, "|") + ")"
}

func releaseBranchPrefix(tagPrefix string) string {
	return "release-" + tagPrefix
}

func releaseBranchRuleRegex(tagPrefix string) string {
	return releaseTagRuleRegex(releaseBranchPrefix(tagPrefix)) + `[0-9]+\.[0-9]+$`
}

func releaseBranchJobName(id string) string {
	switch id {
	case "nvcf-compute-plane-stack":
		return "release-branch-compute-stack"
	default:
		return "release-branch-" + id
	}
}

func renderGitHubReleaseMetadata(cfg configFile, configPath string) ([]byte, error) {
	metadata := githubReleaseMetadata{
		Version:               1,
		GeneratedBy:           fmt.Sprintf("go run -C tools/generate-subproject-ci . --config %s --github-release-output ../ci/github-release-subprojects.json", configPath),
		ReleaseGeneratedPaths: releaseGeneratedPaths(cfg.ReleaseGeneratedPaths),
	}

	for _, sp := range cfg.Subprojects {
		if sp.Release == nil {
			continue
		}
		releasePath := releasePathForSubproject(sp)
		tagFormat := ""
		if strings.TrimSpace(sp.Release.TagFormat) != "" {
			tagFormat = releaseTagFormat(sp.Release, releasePath)
		}
		metadata.Services = append(metadata.Services, githubReleaseMetadataService{
			ID:                          sp.ID,
			Path:                        releasePath,
			ServiceName:                 strings.TrimSpace(sp.Release.ServiceName),
			TagFormat:                   tagFormat,
			LegacyTagPrefix:             legacyTagPrefix(sp.Release),
			VersionFile:                 strings.TrimSpace(sp.Release.VersionFile),
			VersionMajorMinorSourceFile: strings.TrimSpace(sp.Release.VersionMajorMinorSourceFile),
			DevPrerelease:               sp.Release.DevPrerelease,
		})
	}

	rendered, err := json.MarshalIndent(metadata, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(rendered, '\n'), nil
}

// renderReleasePipeline returns the YAML body of the release-jobs
// file (typically tools/ci/generated-release-jobs.yml). The umbrella
// .gitlab-ci.yml `include: local: ...`s this file. One block per
// subproject that declared `release:` in subproject-validations.yaml.
func renderReleasePipeline(cfg configFile, configPath string) (string, error) {
	view := releasePipelineView{
		ConfigPath:          configPath,
		GeneratedPathsRegex: generatedPathsRegex(cfg.ReleaseGeneratedPaths),
	}

	for _, sp := range cfg.Subprojects {
		if sp.Release == nil {
			continue
		}

		// YAML anchor names allow a-zA-Z0-9-_ but not all chars; use
		// a sanitized form to stay portable.
		anchor := strings.ReplaceAll(sp.ID, "-", "_") + "_release_paths"

		releasePath := releasePathForSubproject(sp)
		tagFormat := releaseTagFormat(sp.Release, releasePath)
		tagPrefix := releaseTagPrefix(tagFormat)

		svc := releaseServiceView{
			ID:                                 sp.ID,
			ServiceName:                        sp.Release.ServiceName,
			Path:                               releasePath,
			ChangePaths:                        sp.ChangePaths,
			RulesAnchor:                        anchor,
			ReleaseTagFormat:                   tagFormat,
			ReleaseTagPrefix:                   tagPrefix,
			ReleaseTagGlob:                     tagPrefix + "*",
			ReleaseTagRuleRegex:                releaseTagRuleRegex(tagPrefix, legacyTagPrefix(sp.Release)),
			LegacyTagPrefix:                    legacyTagPrefix(sp.Release),
			ReleaseBranchPrefix:                releaseBranchPrefix(tagPrefix),
			ReleaseBranchRuleRegex:             releaseBranchRuleRegex(tagPrefix),
			ReleaseBranchJobName:               releaseBranchJobName(sp.ID),
			EmitReleaseTagPrefix:               tagPrefix != strings.TrimSpace(sp.Release.ServiceName)+"-v",
			InternalRelease:                    sp.Release.InternalRelease != nil,
			ArchiveRelease:                     sp.Release.ArchiveRelease != nil,
			SlackChannel:                       sp.Release.SlackChannel,
			NeedsHostGo:                        sp.NeedsHostGo,
			ReleaseVersionFile:                 strings.TrimSpace(sp.Release.VersionFile),
			ReleaseVersionFilePath:             path.Join(releasePath, strings.TrimSpace(sp.Release.VersionFile)),
			ReleaseVersionMajorMinorSourceFile: strings.TrimSpace(sp.Release.VersionMajorMinorSourceFile),
			ReleaseDevPrerelease:               sp.Release.DevPrerelease,
			ReleaseRCPrerelease:                sp.Release.RCPrerelease,
		}

		for _, t := range sp.Release.ImagePushTargets {
			svc.Targets = append(svc.Targets, releaseTargetView{
				Name:           t.Name,
				BazelTarget:    t.BazelTarget,
				AuthType:       t.Auth.Type,
				CIVar:          t.Auth.CIVar,
				DockerAuthPath: t.DockerAuthPath,
			})
			switch t.Auth.Type {
			case "vault":
				if !svc.HasVaultTarget {
					svc.HasVaultTarget = true
					svc.VaultKey = t.Auth.VaultKey
				}
			case "vault_ncp_dev":
				svc.HasVaultNcpDev = true
			}
		}

		// Dedupe ci_var names across targets so the template emits one
		// "is var set" guard per unique variable. Order preserved by
		// first-seen across image_push_targets.
		seenCIVar := map[string]struct{}{}
		for _, t := range sp.Release.ImagePushTargets {
			if t.Auth.Type != "ci_var" {
				continue
			}
			if _, ok := seenCIVar[t.Auth.CIVar]; ok {
				continue
			}
			seenCIVar[t.Auth.CIVar] = struct{}{}
			svc.CIVars = append(svc.CIVars, t.Auth.CIVar)
		}

		if sp.Release.Staging != nil {
			staging := &releaseStagingView{}
			for _, image := range sp.Release.Staging.Images {
				targetName := sanitizeBazelTargetName("push_" + image.Name)
				iv := releaseStagingImageView{
					Name:             image.Name,
					TargetName:       targetName,
					BazelImageTarget: image.BazelImageTarget,
					StageJobName:     sanitizeJobName(sp.ID + "-stage-" + image.Name),
					ArtifactPath:     path.Join("release-images", targetName+".json"),
				}
				for _, mt := range image.MrPushTargets {
					repoSanitized := sanitizeBazelTargetName(strings.ReplaceAll(mt.Repository, "nvcr.io/", ""))
					mv := releaseStagingMrPushTargetView{
						Repository:       mt.Repository,
						BazelImageTarget: image.BazelImageTarget,
						BazelTargetName:  sanitizeBazelTargetName("push_mr_" + repoSanitized),
						AuthType:         mt.Auth.Type,
					}
					if mt.Auth.Type == "vault" {
						mv.VaultKey = mt.Auth.VaultKey
						mv.TokenEnvVar = strings.ToUpper(strings.ReplaceAll(mt.Auth.VaultKey, "-", "_")) + "_TOKEN"
					}
					iv.MrPushTargets = append(iv.MrPushTargets, mv)
				}
				staging.Images = append(staging.Images, iv)
			}
			svc.Staging = staging
		}

		if sp.Release.Helm != nil {
			helmView := &releaseHelmView{
				ChartPath: path.Join(sp.Path, sp.Release.Helm.ChartPath),
				Lint:      sp.Release.Helm.Lint,
			}
			for _, t := range sp.Release.Helm.PushTargets {
				// One of NGCPath / NGCPathVar is set (enforced by
				// validateRelease). NGCPathVar takes a `$VARNAME` shape
				// so the cds-component expands it via its `expand_vars`
				// input filter at pipeline runtime.
				ngcPath := t.NGCPath
				if ngcPath == "" {
					ngcPath = "$" + t.NGCPathVar
				}
				// Resolve auth: prefer the explicit Auth block; fall
				// back to the legacy NGCKeyVar field (treated as
				// type=ci_var). HasVaultNcpDev is set only on the
				// helm view (helmView), NOT on the parent svc, so a
				// service whose helm targets use vault_ncp_dev but
				// whose image targets use ci_var does NOT also wire
				// the ncp-dev vault fetch into the image-push job's
				// SECRETS_TO_RETRIEVE_IN_JSON.
				var authType, ngcKeyEnvVar string
				if t.Auth != nil {
					authType = t.Auth.Type
					switch authType {
					case "ci_var":
						ngcKeyEnvVar = t.Auth.CIVar
					case "vault_ncp_dev":
						ngcKeyEnvVar = ncpDevServiceKeyEnvVar
					}
				} else {
					authType = "ci_var"
					ngcKeyEnvVar = t.NGCKeyVar
				}
				helmView.PushTargets = append(helmView.PushTargets, releaseHelmTargetView{
					Name:            t.Name,
					NGCPath:         ngcPath,
					NGCKeyEnvVar:    ngcKeyEnvVar,
					AuthType:        authType,
					ClassicRegistry: t.ClassicRegistry,
				})
				if authType == "vault_ncp_dev" {
					helmView.HasVaultNcpDev = true
				}
				if t.ClassicRegistry {
					helmView.HasClassic = true
				}
			}
			svc.Helm = helmView
		}

		if sp.Release.Dockerfile != nil {
			ctx := strings.TrimSpace(sp.Release.Dockerfile.ContextPath)
			if ctx == "" {
				ctx = "."
			}
			dockerfile := strings.TrimSpace(sp.Release.Dockerfile.Dockerfile)
			if dockerfile == "" {
				dockerfile = "Dockerfile"
			}
			ncpDev := strings.TrimSpace(sp.Release.Dockerfile.NCPDevPath)
			if ncpDev == "" {
				// Default ncp-dev tenant; matches every other umbrella-native
				// service's vault_ncp_dev push destination.
				ncpDev = "0651155215864979/ncp-dev"
			}
			// Pre-join the context path onto the subtree root so the
			// generated YAML's `cd <context>` line takes the buildah
			// invocation directly to the buildah build directory from
			// the umbrella repo root.
			joinedContext := ctx
			if ctx == "." {
				joinedContext = sp.Path
			} else {
				joinedContext = path.Join(sp.Path, ctx)
			}
			// Resolve to a uniform image list so the template renders the
			// same commands for single-image services (one entry, empty
			// Target -> no `--target`) and multi-target ones.
			var dfImages []releaseDockerfileImageView
			if len(sp.Release.Dockerfile.Images) > 0 {
				for _, im := range sp.Release.Dockerfile.Images {
					dfImages = append(dfImages, releaseDockerfileImageView{Name: im.Name, Target: im.Target})
				}
			} else {
				dfImages = []releaseDockerfileImageView{{Name: sp.Release.Dockerfile.ImageName}}
			}
			svc.Dockerfile = &releaseDockerfileView{
				ContextPath:   joinedContext,
				Dockerfile:    dockerfile,
				ImageName:     sp.Release.Dockerfile.ImageName,
				Images:        dfImages,
				NCPDevPath:    ncpDev,
				AnonymousBase: sp.Release.Dockerfile.AnonymousBase,
			}
		}

		view.Services = append(view.Services, svc)
	}

	tmpl, err := template.New("release-pipeline").Funcs(template.FuncMap{
		"yamlValue": yamlScalar,
		"upper":     strings.ToUpper,
	}).Parse(releasePipelineTemplate)
	if err != nil {
		return "", err
	}

	var buf strings.Builder
	if err := tmpl.Execute(&buf, view); err != nil {
		return "", err
	}
	return buf.String(), nil
}

func renderGoWork(cfg configFile, configPath string) (string, error) {
	if cfg.GoWork == nil {
		return "", errors.New("go_work is not configured")
	}

	useSet := map[string]struct{}{}
	for _, path := range cfg.GoWork.Use {
		trimmed := filepath.ToSlash(strings.TrimSpace(path))
		trimmed = strings.TrimPrefix(trimmed, "./")
		if trimmed == "" {
			continue
		}
		useSet[trimmed] = struct{}{}
	}
	for _, subproject := range cfg.Subprojects {
		if !subproject.GoWork {
			continue
		}
		trimmed := filepath.ToSlash(strings.TrimSpace(subproject.Path))
		trimmed = strings.TrimPrefix(trimmed, "./")
		if trimmed == "" {
			continue
		}
		useSet[trimmed] = struct{}{}
	}

	if len(useSet) == 0 {
		return "", errors.New("go_work has no modules to include")
	}

	usePaths := make([]string, 0, len(useSet))
	for path := range useSet {
		usePaths = append(usePaths, path)
	}
	sort.Strings(usePaths)

	view := struct {
		ConfigPath string
		GoVersion  string
		Use        []string
	}{
		ConfigPath: configPath,
		GoVersion:  cfg.GoWork.Go,
		Use:        usePaths,
	}

	tmpl, err := template.New("goWork").Parse(goWorkTemplate)
	if err != nil {
		return "", err
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, view); err != nil {
		return "", err
	}
	return buf.String(), nil
}

func buildBazelJob(sharedChangePaths []string, subproject subproject) generatedJob {
	changes := []string{}
	if !subproject.SkipSharedChangePaths {
		changes = append(changes, sharedChangePaths...)
	}
	if len(subproject.ChangePaths) > 0 {
		changes = append(changes, subproject.ChangePaths...)
	} else {
		changes = append(changes, filepath.ToSlash(filepath.Join(subproject.Path, "**/*")))
	}

	job := generatedJob{
		Name:    sanitizeJobName(subproject.ID + "-bazel-build-test"),
		Extends: ".bazel-subtree",
		Variables: map[string]string{
			"SUBTREE": subproject.Path,
		},
		Changes:            changes,
		SkipGlobalTriggers: subproject.SkipGlobalTriggers,
	}

	if subproject.Bazel != nil && subproject.Bazel.Dind {
		job.Tags = []string{"dind", "eks", "nvcf-cds", "prod"}
		job.Services = []generatedService{
			{
				Name:    "docker:dind",
				Command: []string{"--tls=false"},
			},
		}
		job.Variables["DOCKER_HOST"] = "tcp://docker:2375"
		job.Variables["DOCKER_TLS_CERTDIR"] = ""
		job.Variables["NVCF_BAZEL_DIND"] = "1"
		job.Variables["TESTCONTAINERS_RYUK_DISABLED"] = "true"
	}
	if subproject.Bazel != nil && len(subproject.Bazel.ExtraTestTargets) > 0 {
		job.Variables["BAZEL_SUBTREE_EXTRA_TEST_TARGETS"] = strings.Join(subproject.Bazel.ExtraTestTargets, " ")
	}
	if subproject.Bazel != nil && len(subproject.Bazel.ExtraBuildTargets) > 0 {
		targets := make([]string, 0, len(subproject.Bazel.ExtraBuildTargets))
		for _, target := range subproject.Bazel.ExtraBuildTargets {
			targets = append(targets, strings.TrimSpace(target))
		}
		job.Variables["BAZEL_SUBTREE_EXTRA_BUILD_TARGETS"] = strings.Join(targets, " ")
	}
	if subproject.Bazel != nil && subproject.Bazel.SetupEnvtest {
		job.Variables["NVCF_BAZEL_SETUP_ENVTEST"] = "1"
	}

	// Opt this service into .bazel-subtree's host-Go install. The
	// before_script gates the actual download on this env var so the
	// majority of services (which use rules_go's downloaded SDK) do
	// not hit go.dev on every CI run.
	if subproject.NeedsHostGo {
		job.Variables["INSTALL_GO"] = "1"
	}

	if subproject.Bazel != nil && len(subproject.Bazel.Targets) > 0 {
		targets := make([]string, 0, len(subproject.Bazel.Targets))
		for _, target := range subproject.Bazel.Targets {
			targets = append(targets, strings.TrimSpace(target))
		}
		targetPatterns := strings.Join(targets, " ")
		job.Script = []string{
			fmt.Sprintf("bazel build %s ${BAZEL_REMOTE_FLAGS}", targetPatterns),
			fmt.Sprintf("bazel test %s ${BAZEL_REMOTE_FLAGS} --flaky_test_attempts=3", targetPatterns),
			`if [ -n "${BAZEL_SUBTREE_EXTRA_BUILD_TARGETS:-}" ]; then bazel build ${BAZEL_SUBTREE_EXTRA_BUILD_TARGETS} ${BAZEL_REMOTE_FLAGS}; fi`,
		}
	}

	return job
}

func buildHelmValidateJob(sharedChangePaths []string, subproject subproject) (generatedJob, error) {
	chartPath, err := helmValidateChartPath(subproject)
	if err != nil {
		return generatedJob{}, err
	}

	changes := []string{}
	if !subproject.SkipSharedChangePaths {
		changes = append(changes, sharedChangePaths...)
	}
	if len(subproject.ChangePaths) > 0 {
		changes = append(changes, subproject.ChangePaths...)
	} else {
		changes = append(changes, filepath.ToSlash(filepath.Join(subproject.Path, "**/*")))
	}

	command := fmt.Sprintf(
		`cd "$CI_PROJECT_DIR/%s" && apk add --no-cache helm && "$CI_PROJECT_DIR/tools/ci/validate-helm-chart.sh" %s`,
		subproject.Path,
		shellQuote(chartPath),
	)
	if valuesFile := strings.TrimSpace(subproject.HelmValidate.ValuesFile); valuesFile != "" {
		command += fmt.Sprintf(` -f "$CI_PROJECT_DIR/%s"`, filepath.ToSlash(valuesFile))
	}

	return generatedJob{
		Name:               sanitizeJobName(subproject.ID + "-helm-lint-template"),
		Stage:              "validate",
		Image:              "alpine:3.20",
		Changes:            changes,
		SkipGlobalTriggers: subproject.SkipGlobalTriggers,
		Script:             []string{command},
	}, nil
}

func helmValidateChartPath(subproject subproject) (string, error) {
	if subproject.HelmValidate == nil {
		return "", fmt.Errorf("subproject %q helm_validate is not configured", subproject.ID)
	}
	if chartPath := strings.TrimSpace(subproject.HelmValidate.ChartPath); chartPath != "" {
		return chartPath, nil
	}
	if subproject.Release != nil && subproject.Release.Helm != nil {
		if chartPath := strings.TrimSpace(subproject.Release.Helm.ChartPath); chartPath != "" {
			return chartPath, nil
		}
	}
	return "", fmt.Errorf("subproject %q helm_validate.chart_path must be set when release.helm.chart_path is unavailable", subproject.ID)
}

func buildJob(sharedChangePaths []string, profile profile, subproject subproject, chk check) (generatedJob, error) {
	data := subprojectTemplateData{
		ID:   subproject.ID,
		Path: subproject.Path,
	}

	jobName := sanitizeJobName(subproject.ID + "-" + chk.ID)
	stage := profile.Stage
	if strings.TrimSpace(stage) == "" {
		stage = "validate"
	}

	script, err := buildScript(profile, data, chk)
	if err != nil {
		return generatedJob{}, err
	}

	changes := []string{}
	if !subproject.SkipSharedChangePaths {
		changes = append(changes, sharedChangePaths...)
	}
	if len(subproject.ChangePaths) > 0 {
		changes = append(changes, subproject.ChangePaths...)
	} else {
		changes = append(changes, filepath.ToSlash(filepath.Join(subproject.Path, "**/*")))
	}

	image := profile.Image
	if strings.TrimSpace(chk.Image) != "" {
		image = chk.Image
	}

	job := generatedJob{
		Name:               jobName,
		Stage:              stage,
		Extends:            profile.Extends,
		Image:              image,
		Variables:          profile.Variables,
		Changes:            changes,
		SkipGlobalTriggers: subproject.SkipGlobalTriggers,
		Script:             script,
	}

	if strings.TrimSpace(chk.Coverage) != "" {
		job.Coverage, err = renderTemplateString(chk.Coverage, data)
		if err != nil {
			return generatedJob{}, fmt.Errorf("job %q coverage: %w", jobName, err)
		}
	}
	if len(chk.Artifacts) > 0 {
		paths := make([]string, 0, len(chk.Artifacts))
		for _, artifactPath := range chk.Artifacts {
			rendered, err := renderTemplateString(artifactPath, data)
			if err != nil {
				return generatedJob{}, fmt.Errorf("job %q artifact path: %w", jobName, err)
			}
			paths = append(paths, rendered)
		}
		expireIn := chk.ExpireIn
		if strings.TrimSpace(expireIn) == "" {
			expireIn = "30 days"
		}
		job.Artifacts = &artifacts{
			Paths:    paths,
			ExpireIn: expireIn,
		}
	}

	return job, nil
}

func buildScript(profile profile, subproject subprojectTemplateData, chk check) ([]string, error) {
	prefix := workspaceSetupScript(profile, chk)

	switch chk.Type {
	case "go-vendor":
		return append(prefix,
			fmt.Sprintf("./tools/ci/check-go-vendor %s", shellQuote(subproject.Path)),
		), nil
	case "go-codegen":
		command, err := renderTemplateString(chk.Command, subproject)
		if err != nil {
			return nil, err
		}
		line := fmt.Sprintf("./tools/ci/check-go-codegen %s --command %s", shellQuote(subproject.Path), shellQuote(command))
		for _, install := range chk.Install {
			expanded, err := renderTemplateString(install, subproject)
			if err != nil {
				return nil, err
			}
			line += " --install " + shellQuote(expanded)
		}
		return append(prefix, line), nil
	case "go-unit-tests":
		resultsDir := chk.ResultsDir
		if strings.TrimSpace(resultsDir) == "" {
			resultsDir = filepath.ToSlash(filepath.Join("public", subproject.ID))
		}
		expandedResults, err := renderTemplateString(resultsDir, subproject)
		if err != nil {
			return nil, err
		}
		return append(prefix,
			fmt.Sprintf("./tools/ci/run-go-unit-tests %s --results-dir %s", shellQuote(subproject.Path), shellQuote(expandedResults)),
		), nil
	case "shell":
		command, err := renderTemplateString(chk.Command, subproject)
		if err != nil {
			return nil, err
		}
		return append(prefix,
			fmt.Sprintf("cd \"$CI_PROJECT_DIR/%s\" && %s", subproject.Path, command),
		), nil
	case "go-workspace-shell":
		command, err := renderTemplateString(chk.Command, subproject)
		if err != nil {
			return nil, err
		}
		return append(prefix,
			fmt.Sprintf("cd \"$CI_PROJECT_DIR/%s\" && GOWORK=\"$CI_PROJECT_DIR/go.work\" %s", subproject.Path, command),
		), nil
	default:
		return nil, fmt.Errorf("unsupported check type %q", chk.Type)
	}
}

func workspaceSetupScript(profile profile, chk check) []string {
	if chk.SkipWorkspaceSetup {
		return nil
	}

	if chk.Type == "go-workspace-shell" {
		return []string{"./tools/scripts/update-go-work"}
	}

	gowork, ok := profile.Variables["GOWORK"]
	if !ok {
		return nil
	}

	trimmed := strings.TrimSpace(gowork)
	if trimmed == "" || trimmed == "off" {
		return nil
	}

	return []string{"./tools/scripts/update-go-work"}
}

func renderTemplateString(input string, data subprojectTemplateData) (string, error) {
	tmpl, err := template.New("value").Option("missingkey=error").Parse(input)
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", err
	}
	return buf.String(), nil
}

func sanitizeJobName(value string) string {
	lower := strings.ToLower(value)
	re := regexp.MustCompile(`[^a-z0-9]+`)
	lower = re.ReplaceAllString(lower, "-")
	lower = strings.Trim(lower, "-")
	if lower == "" {
		return "subproject-validation"
	}
	return lower
}

func sanitizeBazelTargetName(value string) string {
	lower := strings.ToLower(value)
	re := regexp.MustCompile(`[^a-z0-9_]+`)
	lower = re.ReplaceAllString(lower, "_")
	lower = strings.Trim(lower, "_")
	if lower == "" {
		return "target"
	}
	return lower
}

func shellQuote(value string) string {
	if value == "" {
		return "''"
	}
	return "'" + strings.ReplaceAll(value, "'", `'"'"'`) + "'"
}

func yamlScalar(value any) string {
	raw, err := yaml.Marshal(value)
	if err != nil {
		panic(err)
	}
	return strings.TrimSpace(string(raw))
}

func yamlListItem(value any, indent int) string {
	scalar := yamlScalar(value)
	lines := strings.Split(scalar, "\n")
	prefix := strings.Repeat(" ", indent)
	if len(lines) == 1 {
		return prefix + "- " + lines[0]
	}

	var out strings.Builder
	out.WriteString(prefix)
	out.WriteString("- ")
	out.WriteString(lines[0])
	for _, line := range lines[1:] {
		out.WriteString("\n")
		out.WriteString(prefix)
		out.WriteString("  ")
		out.WriteString(line)
	}
	return out.String()
}

func sortMap(values map[string]string) []keyValue {
	if len(values) == 0 {
		return nil
	}
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)

	out := make([]keyValue, 0, len(keys))
	for _, key := range keys {
		out = append(out, keyValue{Key: key, Value: values[key]})
	}
	return out
}
